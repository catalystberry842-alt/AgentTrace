import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import solc from "solc";

const root = join(import.meta.dirname, "..");
const contractsDir = join(root, "contracts");

function load(name) {
  const source = readFileSync(join(contractsDir, name), "utf8");
  if (/\btx\.origin\b/.test(source) || /\bdelegatecall\b/.test(source)) {
    console.error(`${name} uses a forbidden pattern`);
    process.exit(1);
  }
  return source;
}

const sources = {
  "AgentRegistry.sol": { content: load("AgentRegistry.sol") },
  "AgentFirewall.sol": { content: load("AgentFirewall.sol") },
  "AgentProof.sol": { content: load("AgentProof.sol") },
  "DemoProtocol.sol": { content: load("DemoProtocol.sol") },
};

const input = {
  language: "Solidity",
  sources,
  settings: {
    optimizer: { enabled: true, runs: 200 },
    viaIR: true,
    outputSelection: {
      "*": { "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object"] },
    },
  },
};

const output = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = (output.errors ?? []).filter((e) => e.severity === "error");
if (errors.length) {
  for (const error of errors) console.error(error.formattedMessage);
  process.exit(1);
}

function artifactFor(file, name, requiredEvents, requiredFns) {
  const compiled = output.contracts[file][name];
  if (!compiled?.evm?.bytecode?.object) {
    console.error(`Compiler returned no bytecode for ${name}`);
    process.exit(1);
  }
  const abi = compiled.abi;
  const events = new Set(abi.filter((item) => item.type === "event").map((item) => item.name));
  for (const required of requiredEvents) {
    if (!events.has(required)) {
      console.error(`${name} missing event ${required}`);
      process.exit(1);
    }
  }
  const functions = new Set(abi.filter((item) => item.type === "function").map((item) => item.name));
  for (const required of requiredFns) {
    if (!functions.has(required)) {
      console.error(`${name} missing function ${required}`);
      process.exit(1);
    }
  }
  if ([...functions].some((fn) => /upgrade|setAdmin|changeAdmin/i.test(fn))) {
    console.error(`${name} exposes an admin or upgrade function`);
    process.exit(1);
  }
  return {
    contractName: name,
    compiler: solc.version(),
    abi,
    bytecode: `0x${compiled.evm.bytecode.object}`,
    deployedBytecode: `0x${compiled.evm.deployedBytecode.object}`,
  };
}

const registry = artifactFor(
  "AgentRegistry.sol",
  "AgentRegistry",
  ["AgentRegistered", "AgentUpdated", "AgentDeactivated"],
  [
    "registerAgent",
    "getAgent",
    "getAgentCount",
    "getAgentsByOwner",
    "agentExists",
    "getAgentOwner",
    "updateAgentMetadata",
    "deactivateAgent",
  ],
);

const firewall = artifactFor(
  "AgentFirewall.sol",
  "AgentFirewall",
  [
    "FirewallCreated",
    "ExecutorUpdated",
    "TargetAllowed",
    "TargetDisabled",
    "FunctionAllowed",
    "FunctionDisabled",
    "AgentAction",
    "FirewallPaused",
    "FirewallUnpaused",
    "FirewallDeactivated",
    "PolicyUpdated",
  ],
  [
    "createFirewall",
    "setExecutor",
    "updatePolicy",
    "allowTarget",
    "disableTarget",
    "allowFunction",
    "disableFunction",
    "pauseFirewall",
    "unpauseFirewall",
    "deactivateFirewall",
    "execute",
    "getFirewall",
    "getPolicy",
    "getFirewallsByAgent",
  ],
);

const proof = artifactFor(
  "AgentProof.sol",
  "AgentProof",
  ["ExecutionProofAnchored"],
  ["anchorProof", "getAnchor", "isAnchored", "setVerifier"],
);

const demo = artifactFor(
  "DemoProtocol.sol",
  "DemoProtocol",
  ["Deposited", "Withdrawn", "Swapped"],
  ["deposit", "swap", "withdraw"],
);

const outDir = join(contractsDir, "out");
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, "AgentRegistry.json"), JSON.stringify(registry, null, 2));
writeFileSync(join(outDir, "AgentFirewall.json"), JSON.stringify(firewall, null, 2));
writeFileSync(join(outDir, "AgentProof.json"), JSON.stringify(proof, null, 2));
writeFileSync(join(outDir, "DemoProtocol.json"), JSON.stringify(demo, null, 2));

const abiTs = `/* Generated by scripts/compile-registry.mjs — do not edit by hand. */
export const agentRegistryAbi = ${JSON.stringify(registry.abi, null, 2)} as const;

export const agentFirewallAbi = ${JSON.stringify(firewall.abi, null, 2)} as const;

export const agentProofAbi = ${JSON.stringify(proof.abi, null, 2)} as const;

export const demoProtocolAbi = ${JSON.stringify(demo.abi, null, 2)} as const;
`;
writeFileSync(join(root, "src", "lib", "chain", "abi.ts"), abiTs);

const registryBytes = registry.bytecode.length / 2 - 1;
const firewallBytes = firewall.bytecode.length / 2 - 1;
const proofBytes = proof.bytecode.length / 2 - 1;
const demoBytes = demo.bytecode.length / 2 - 1;
console.log(`compiled AgentRegistry abi=${registry.abi.length} bytecode=${registryBytes} bytes`);
console.log(`compiled AgentFirewall abi=${firewall.abi.length} bytecode=${firewallBytes} bytes`);
console.log(`compiled AgentProof abi=${proof.abi.length} bytecode=${proofBytes} bytes`);
console.log(`compiled DemoProtocol abi=${demo.abi.length} bytecode=${demoBytes} bytes`);
if (firewallBytes > 24_576 || proofBytes > 24_576 || demoBytes > 24_576) {
  console.error("Contract bytecode exceeds 24576 bytes");
  process.exit(1);
}
